using LoomKit.Workflows.Models;

namespace LoomKit.Workflows.Contracts;

// Covariant on TNext: IWorkflowStep<SendEmailActivity, OrderCtx> IS-A IWorkflowStep<IActivity<OrderCtx>, OrderCtx>
public interface IWorkflowStep<out TNext, TWorkflowContext>
    where TNext : IActivity<TWorkflowContext>
    where TWorkflowContext : IWorkflowContext
{
    TWorkflowContext? Context { get; }
}

// Non-generic interface for consumer dispatch: allows accessing Next/ResumeTokens/NextAt without knowing TNext
public interface IWorkflowNextStep
{
    IActivity NextActivity { get; }
    IWorkflowContext? NextContext { get; }
    bool IsPaused { get; }
    IReadOnlyList<ResumeToken>? ResumeTokens { get; }

    // When null, the next activity is enqueued immediately (today's behavior). When set, it becomes
    // the enqueued schedule's NextAt, letting a handler implement bounded polling/timeout patterns
    // (e.g. "recheck in 30s") without any relation to unbounded cron-style recurrence.
    DateTime? NextAt { get; }
}

// Non-generic interface for fork dispatch: allows accessing all branches, the ForkId, and the
// optional join-point activity without knowing TWorkflowContext
public interface IWorkflowForkStep
{
    string ForkId { get; }
    IEnumerable<IWorkflowForkBranch> Branches { get; }
    IWorkflowContext? NextContext { get; }

    // Null: the fork is "throwaway" like a plain fork - every branch runs independently to its own
    // WorkflowEnd, nobody waits for anybody. Non-null: this activity is also enqueued, paused, as the
    // fork's join point (ForkId set, JoinId null on its own schedule), waiting for branches to report
    // in via WorkflowJoin. See Models/WorkflowStep.cs.
    IActivity? JoinPointActivity { get; }
}

// One branch of a fork, paired with the JoinId slot it was assigned at fork time (the fork author
// decides the JoinId upfront, e.g. "payment"/"inventory" - it is not generated by the branch itself)
public interface IWorkflowForkBranch
{
    // Null is fine for a throwaway fork branch (no JoinPointActivity, nobody cares about the slot
    // name). Required only when the fork also sets JoinPointActivity and this branch matters to it.
    string? JoinId { get; }
    IActivity Activity { get; }
}

// Non-generic interface for a join-point activity's "not enough arrivals yet, keep waiting" outcome.
// Structurally a sibling of IWorkflowNextStep/WorkflowPause but woken by sibling branch arrivals on
// its ForkId's inbox instead of an externally-triggered ResumeToken.
public interface IWorkflowJoinWaitStep
{
    IActivity NextActivity { get; }
    IWorkflowContext? NextContext { get; }
}
